const toTw = OpenCC.Converter({ from: 'cn', to: 'twp' });
const zhTw: Dict = Object.fromEntries(Object.entries(zh).map(([k, v]) => [k, /^[\x00-\x7f]*$/.test(v) ? v : twFix(toTw(v))]));
const zhFixed: Dict = Object.fromEntries(Object.entries(zh).map(([k, v]) => [k, twFix(v)]));
// zh follows Taiwan-server terminology like the rest of the site (Stamina = 持久力 ...), applied by twFix.
export const SCHEDULE_STRINGS: Record<Locale, Dict> = { en, ja, zh: zhFixed, 'zh-tw': zhTw, ko };

export function st(locale: Locale, key: string, vars: Record<string, string | number> = {}): string {
  let v = SCHEDULE_STRINGS[locale]?.[key] ?? en[key] ?? key;
  for (const [k, val] of Object.entries(vars)) v = v.split(`{${k}}`).join(String(val));
  return v;
}
